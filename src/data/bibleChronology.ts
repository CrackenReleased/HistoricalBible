export type BibleSortMode = 'canonical' | 'event' | 'written';

export function getSortedBooks(mode: BibleSortMode): BookChronology[] {
  const books = [...BIBLE_CHRONOLOGY];
  if (mode === 'event') {
    return books.sort((a, b) => a.eventOrder - b.eventOrder);
  }
  if (mode === 'written') {
    return books.sort((a, b) => a.writtenOrder - b.writtenOrder);
  }
  return books.sort((a, b) => a.canonicalOrder - b.canonicalOrder);
}

export function getBookChronology(bookOrOsis: string): BookChronology | null {
  const clean = bookOrOsis.trim().toLowerCase();
  return (
    BIBLE_CHRONOLOGY.find(
      (b) => b.osis.toLowerCase() === clean || b.name.toLowerCase() === clean
    ) || null
  );
}

export interface ChapterChronologyInfo {
  eventDateLabel: string;
  eraName: string;
  chapterSummary: string;
  bookSpanLabel: string;
  isGranular: boolean;
}

export function getChapterChronology(
  bookOrOsis: string,
  chapter: number
): ChapterChronologyInfo | null {
  const book = getBookChronology(bookOrOsis);
  if (!book) return null;

  if (book.chapterBreakdown && book.chapterBreakdown.length > 0) {
    const match = book.chapterBreakdown.find(
      (b) => chapter >= b.startChapter && chapter <= b.endChapter
    );
    if (match) {
      return {
        eventDateLabel: match.eventDateLabel,
        eraName: match.eraName,
        chapterSummary: match.summary,
        bookSpanLabel: book.eventDateLabel,
        isGranular: true
      };
    }
  }

  return {
    eventDateLabel: book.eventDateLabel,
    eraName: book.eventEraName,
    chapterSummary: book.eventSummary,
    bookSpanLabel: book.eventDateLabel,
    isGranular: false
  };
}
